from playwright.sync_api import sync_playwright
import os
from pathlib import Path
OUT=Path(os.environ.get('QA_OUT_DIR',str(Path(__file__).resolve().parents[1]/'qa')))
OUT.mkdir(parents=True,exist_ok=True)
BASE_URL=os.environ.get('BYTEPETS_URL','http://127.0.0.1:4173')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1460,'height':950},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(BASE_URL,wait_until='networkidle')
 page.screenshot(path=str(OUT/'onboarding.png'),full_page=True)
 page.locator('input[name=username]').fill('teste_visual_23')
 page.locator('input[name=password]').fill('SenhaVisual09')
 page.locator('input[name=petName]').fill('Lumi')
 page.locator('button[type=submit]').click()
 page.locator('.hero-stage').wait_for(timeout=15000)
 page.screenshot(path=str(OUT/'home.png'),full_page=True)
 page.get_by_role('button',name='▣ Jogos').click()
 page.screenshot(path=str(OUT/'games.png'),full_page=True)
 page.get_by_role('button',name='▶ Jogar agora').first.click()
 page.screenshot(path=str(OUT/'pattern.png'),full_page=True)
 page.locator('[data-action="game-answer"]').first.click()
 page.get_by_role('button',name='◈ Loja').click()
 page.screenshot(path=str(OUT/'shop.png'),full_page=True)
 page.get_by_role('button',name='◈ Mundos').click()
 page.screenshot(path=str(OUT/'worlds.png'),full_page=True)
 page.get_by_role('button',name='✎ Desafios').click()
 page.screenshot(path=str(OUT/'challenges.png'),full_page=True)
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 mobile.goto(BASE_URL,wait_until='networkidle')
 mobile.locator('input[name=username]').fill('teste_visual_23')
 mobile.locator('input[name=password]').fill('SenhaVisual09')
 mobile.locator('button[data-action=login-mode]').click()
 mobile.locator('input[name=username]').fill('teste_visual_23')
 mobile.locator('input[name=password]').fill('SenhaVisual09')
 mobile.locator('button[type=submit]').click()
 mobile.locator('.hero-stage').wait_for()
 mobile.screenshot(path=str(OUT/'mobile.png'),full_page=True)
 print('JS ERRORS',errors)
 print('MOBILE horizontal overflow?',mobile.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
 browser.close()
